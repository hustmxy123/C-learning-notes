#include<stdio.h>
#include<stdlib.h>

int main()
{
	//1.malloc函数的应用
	//申请一片空间，存储10个int类型的数据，用数量*sizeof更具通用性
	int* p1 = malloc(10 * sizeof(int));//malloc函数返回的是申请的这片空间的首地址，所以要用指针变量来接收
	//利用循环为这片连续空间赋值（如果不赋值直接打印，会返回乱七八糟的数据，因为malloc函数不具备初始化的功能，calloc才有）
	for (int i = 0; i < 10; i++)
	{
		*(p1 + i) = (i + 1) * 10;//表示空间内连续存放10、20、30、40 ...
		//写法二：p[i] = (i + 1) * 10
		//底层会把p[i]解析成p + i再解引用，因为申请的是一片连续空间，和数组很类似，所以延续了数组的写法
		//当然不是说malloc和数组一样，最大的不同是malloc操作的是堆空间，数组操作的是栈空间，堆空间比栈空间大得多
	}
	//遍历
	for(int i = 0; i < 10; i++)
	{
		printf("%d ", *(p1 + i));
		//写法二：printf("%d ", p[i]);
	}
	printf("\n");

	/*
	//2.calloc函数的应用（malloc更常用，效率更高，而且calloc初始化的数据实际也没用）
	int* p2 = calloc(10, sizeof(int));//底层也会把两个参数相乘
	//可以不赋值直接遍历，会进行初始化，整数 ->0    小数 -> 0.0    字符 -> '\0'等等
	for (int i = 0; i < 10; i++)
	{
		printf("%d ", *(p2 + i));
	}
	*/
	
	//realloc的应用：扩容成20个int类型（也是了解即可，一般malloc申请完很少再修改了）
	int* p2 = realloc(p1, 20 * sizeof(int));//把要扩容空间对应的指针传进去，再输入扩容后的新空间大小
	//很夯的一点是原来存的数据不会丢失，realloc会把它原封不动拷贝到新空间
	//遍历（前十个为已经存入的数据，后十个由于没赋值所以会是乱七八糟的数据）
	for (int i = 0; i < 20; i++)
	{
		printf("%d ", *(p1 + i));
	}
	printf("\n");

	//free函数的应用（前三个函数用完都离开free，必须释放内存空间）
	free(p2);//把要释放的空间的指针传进去即可，对控制台打印没影响，是在内存中操作
	         //realloc修改之后，无需释放原来的空间，底层会进行处理，所以调用realloc后底层已经把p1释放了，这里只用释放p2
	return 0;
}

/*
动态内存分配常用函数：（均在头文件<stdlib.h>中）
函数名	       完整名称	             作用
malloc	   memory allocation	    申请空间（连续）
calloc	 contiguous allocation	申请空间 + 数据初始化
realloc	    re‑allocation	    修改空间大小
free	        free	            释放空间

动态内存分配使用场景
## 竞赛（蓝桥杯）
中等频率，不是每道题都用，但属于必考知识点
简单题：数组直接写死大小，不用malloc
遇到：输入数据数量不确定、数据量很大的题，就要动态内存
可以偷懒直接开超大全局数组，避开malloc；但选择题、填空题会考malloc/calloc/realloc/free、野指针、内存泄漏

## 以后写项目、工作开发（用到非常多）
1. 不知道要存多少数据，不能写死数组长度，只能malloc
2. 链表、树、图，全部依赖动态内存，每个节点都是malloc出来的
3. free必须配对，忘记释放造成内存泄漏，是真实项目常见bug

## 考试高频坑点
1. malloc返回值要判断是否为NULL，因为内存申请可能会失败
2. calloc会自动初始化为0，malloc不会，里面是垃圾值
3. free之后指针变成野指针，不要再使用
4. realloc传NULL等价于malloc；大小传0等价于free
5. 同一个内存不能free两次，程序直接崩溃

## 简单总结
蓝桥杯刷题可以大量用固定大小数组偷懒
但是链表、数据结构、后期写工程代码，动态内存是绕不开的核心，选择题一定会考
*/

/*
## 动态内存分配的小细节
1，malloc创建空间的单位是字节
   malloc(100)就是100字节，只能存25个int类型而非100个
2，malloc返回的是void类型的指针，没有步长的概念，也无法获取空间中的数据，需要强转
   int* p = malloc(25 * sizeof(int))这一步其实就发生了强转
3，malloc返回的仅仅是首地址，没有总大小，最好定义一个变量记录总大小
   这样便于后续遍历和其他函数使用，如：
   int* p = malloc(25 * sizeof(int))      int size = 25
4，malloc申请的空间不会自动消失，如果不能正确释放，会导致内存泄露
   内存泄露：堆内存失去指针指向，再也无法free
   所以使用完一定记得free(p)
5，malloc申请的空间过多，会产生虚拟内存
   当申请的空间过多，因为每一个内存空间不会在刚申请的时候就立马使用
   所以 c 语言并不会立马就在内存中去开辟空间，而是什么时候存储数据了，才会真正的分配空间（相当于先给一张空头支票）
   目的：为了提高内存的使用效率
6，malloc申请的空间没有初始化值，需要先赋值才能使用

7，free释放完空间之后，空间中数据叫做脏数据，可能为原来的值（操作系统没来得及清空），可能被清空，可能被修改为其他值
   总之free完之后不要再用这些数据
8，calloc就是在malloc的基础上多一个初始化的动作

9，realloc修改之后的空间，地址值有可能发生变化，也有可能不会改变，但是原本的数据不会丢失
   如果原申请空间后面还有位置继续扩容，地址可能就不会变，如果没有就一定会挪动
   如果整个内存都没法再申请那么大的空间，就会返回NULL
10，realloc修改之后，无需释放原来的空间，函数底层会进行处理

## 补充考点）
1. void*本身不能解引用、不能加减偏移，必须强制转换成对应类型指针才有步长
2. free之后原指针变成野指针，笔记只说了脏数据，实际写完free最好手动置NULL
3. realloc返回新指针，一定要接收返回值，不能直接写realloc(p,new_size);，失败会返回NULL，把原来内存弄丢
4. calloc初始化是全部字节置0
*/

