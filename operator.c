/*
++和--放在变量前、后，单独写一行时效果是一样的
后加加：先用后加
先加加：先加后用
*/

/*
## 运算符
==、!=、>、<、>=、<=（1真0假，即：成立结果为1，不成立结果为0）
注： C语言没有布尔类型，条件成立结果是1，不成立是0
     不能连续书写a < b < c，逻辑错误

## 逻辑运算符
&&：与
||：或
! ：取反/非
&&和||具有短路效果，即一旦左边表达式能确定表达式结果，右边就不会再计算了
*/

/*
三元运算符：
关系表达式 ? 表达式1 : 表达式2 ;
int a = 10;
int b = 20;
int c = 30;
int temp = a > b ? a : b;
int max = temp > c ? temp : c;
printf("%d\n", max);
*/

/*
逗号运算符（分隔符）
int i;
printf("%d\n", (i = 3, ++i, i++, i + 5));  记得表达式加小括号！
*/

/*
## 运算符优先级
1. ()：小括号优先级最高
2. 一元运算符：++、--、+、-、!
3. 乘除取余：*、/、%
4. 加减：+、-
5. 大小比较：>、>=、<、<=
6. 相等判断：==、!=
7. 逻辑与：&&
8. 逻辑或：||
9. 三元运算符：  ? :
10. 赋值运算符：=、+=、-=、*=、/=、%=
11. ,：逗号运算符优先级最低

## 核心口诀
小括号 > 一元 > 二元 > 三元
&& > || > 赋值
逗号运算符优先级最低

补充：逗号表达式从左向右依次执行，最终结果为最右侧表达式的值
*/