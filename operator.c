#include<stdio.h>

int main()
{
	// 除法 (/)
	printf("%d\n", 10 / 2); // 5

	// 取余 (%)
	printf("%d\n", 10 % 2); // 0
	printf("%d\n", 10 % 3); // 1

	// 通用细节:
	// 1.整数计算, 结果一定是一个整数
	printf("%d\n", 10 / 3);// 3

	// 2.小数计算, 结果一定是一个小数
	printf("%lf\n", 10.1 + 3.0);

	// 3.整数和小数计算, 结果一定是一个小数
	printf("%lf\n", 10 / 3.0);

	// 4.小数直接参与计算, 结果是有可能不精确的
	printf("%lf\n", 3.33333333333333 + 6.66666666666666);
	printf("%.20lf\n", 10.0 / 3.0);

	/*
	%只能用于整数，不能用于浮点数
    double、float 二进制存储天生存在精度丢失
	%获取余数的正负，和第一个数的符号保持一致
	*/

	//键盘录入三位数，拆分为个十百位后打印在控制台
	int num;
	printf("请输入一个三位整数\n");
	scanf("%d", &num);
	int ge = num % 10;
	int shi = num / 10 % 10;
	int bai = num / 100;
	printf("个位：%d\n", ge);
	printf("十位：%d\n", shi);
	printf("百位：%d\n", bai);

	/*
	键盘录入一个两位整数，要求不能包含7，且不能是7的倍数。如果符合要求，输出 1，不符合要求输出 0
	*/
	int a;
	printf("键盘输入一个两位整数\n");
	scanf("%d", &a);
	if (((a % 10) != 7) && ((a / 10) != 7) && (a % 7 != 0)) 
	{
		printf("1");
	}
	else 
	{
		printf("0");
	}
	return 0;
}

